#!/usr/bin/env node
/**
 * build-i18n.mjs — bundle `locales/<code>/messages.json` into `src/i18n.data.js`
 * (window.DT_LOCALES), loaded by taskpane.html before src/i18n.js.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LOCALES = path.join(ROOT, "locales");
const OUT = path.join(ROOT, "src", "i18n.data.js");

const locales = {};
for (const entry of fs.readdirSync(LOCALES, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const file = path.join(LOCALES, entry.name, "messages.json");
  if (fs.existsSync(file)) locales[entry.name] = JSON.parse(fs.readFileSync(file, "utf8"));
}

fs.writeFileSync(
  OUT,
  [
    "/* Generated by scripts/build-i18n.mjs — do not edit. */",
    "window.DT_LOCALES = " + JSON.stringify(locales) + ";",
    "",
  ].join("\n")
);
console.log(`[build-i18n] ${Object.keys(locales).length} locales → src/i18n.data.js (${(fs.statSync(OUT).size / 1024).toFixed(1)} KB)`);
